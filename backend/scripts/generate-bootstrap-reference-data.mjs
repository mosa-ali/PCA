// Deterministically generates database/live-bootstrap/02_reference_data.sql.
//
// Two, and only two, categories of row belong in this file (never test/demo
// data -- see docs/database/PCA_PRODUCTION_REFERENCE_DATA_MATRIX.csv):
//
// 1. BOOTSTRAP BOOKKEEPING: one row per already-accepted migration file in
//    backend/migrations/, inserted into schema_migrations exactly as
//    backend/scripts/migrate.mjs itself would after applying each file. This
//    is NOT optional: without it, the very next `npm run db:migrate` against
//    the freshly bootstrapped database would see an EMPTY schema_migrations
//    table and try to re-apply migration 0001 (CREATE TABLE schema_migrations
//    among others) against a database where those tables already exist,
//    failing immediately. This was discovered by actually running the
//    backend DB test suite against a bootstrap-created database in this
//    mission, not by inspection.
//
// 2. PRODUCTION REFERENCE DATA: the four tables whose CREATE TABLE is
//    immediately followed by an INSERT in their defining migration --
//    billing_currencies, billing_commercial_markets,
//    billing_country_market_rules, entitlement_defaults (see migrations
//    0006 and 0007). These are lookup/config rows the application cannot
//    function without (e.g. every billing_payment_attempts row has a
//    currency_code FK into billing_currencies), never demo content. Values
//    below were read directly from backend/migrations/0006 and 0007's own
//    INSERT statements, then independently confirmed by querying a
//    from-zero-migrated disposable database.
import { readdir, writeFile } from 'node:fs/promises';

const migrationsDir = new URL('../migrations/', import.meta.url);
const files = (await readdir(migrationsDir)).filter((f) => f.endsWith('.sql')).sort();

const lines = [
  '-- database/live-bootstrap/02_reference_data.sql',
  '-- GENERATED by backend/scripts/generate-bootstrap-reference-data.mjs.',
  '-- Do not hand-edit -- see that script\'s header for what belongs here and why.',
  '--',
  '-- Idempotent-safe: every INSERT below targets a table this bootstrap just',
  '-- created empty, in the same one-time run as 01_create_database_schema.sql.',
  '-- This file must never be re-run against a database that already holds',
  '-- these rows.',
  '',
  '-- =========================================================================',
  '-- 1. Bootstrap bookkeeping: mark every accepted migration as already',
  '--    applied, so the next `npm run db:migrate` only applies NEW migrations',
  '--    (0037+) going forward -- see this script\'s header.',
  '-- =========================================================================',
  'INSERT INTO `schema_migrations` (`version`, `applied_at`) VALUES',
  files.map((f) => `  ('${f}', CURRENT_TIMESTAMP(3))`).join(',\n') + ';',
  '',
  '-- =========================================================================',
  '-- 2. Production reference data (from backend/migrations/0007_billing_core.sql)',
  '-- =========================================================================',
  "INSERT INTO `billing_currencies` (`currency_code`, `minor_unit_exponent`, `enabled`) VALUES",
  "  ('USD', 2, 1),",
  "  ('SAR', 2, 1),",
  "  ('YER', 2, 1);",
  '',
  "INSERT INTO `billing_commercial_markets` (`commercial_market`, `default_currency_code`) VALUES",
  "  ('YEMEN', 'YER'),",
  "  ('GULF', 'SAR'),",
  "  ('GLOBAL_OTHER', 'USD');",
  '',
  "INSERT INTO `billing_country_market_rules` (`country_code`, `commercial_market`) VALUES",
  "  ('YE', 'YEMEN'),",
  "  ('SA', 'GULF'),",
  "  ('AE', 'GULF'),",
  "  ('QA', 'GULF'),",
  "  ('KW', 'GULF'),",
  "  ('BH', 'GULF'),",
  "  ('OM', 'GULF');",
  '',
  '-- =========================================================================',
  '-- 3. Production reference data (from backend/migrations/0006_platform_entitlements_enrollment_limits.sql)',
  '-- =========================================================================',
  "INSERT INTO `entitlement_defaults` (`tier`, `parent_member_limit`, `managed_device_limit`, `updated_at`, `updated_by_admin_id`) VALUES",
  "  ('FREE_STARTER', 1, 1, CURRENT_TIMESTAMP(3), NULL);",
  '',
];

const outPath = new URL('../../database/live-bootstrap/02_reference_data.sql', import.meta.url);
await writeFile(outPath, lines.join('\n'), 'utf8');
console.log(`Wrote database/live-bootstrap/02_reference_data.sql: ${files.length} schema_migrations row(s) + 14 production reference row(s).`);
